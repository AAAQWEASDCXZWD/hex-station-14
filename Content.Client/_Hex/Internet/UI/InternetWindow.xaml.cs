    #region Helpers

    private bool CanPost
    {
        get
        {
            if (_state is not { HasIdCard: true } state)
                return false;

            return state.IdCardName == LocalCharacterName();
        }
    }

    private bool CanEdit(InternetPostInfo post)
    {
        return _playerManager.LocalUser is { } user
               && user == post.AuthorUserId
               && post.AuthorName == LocalCharacterName()
               && _state?.IdCardName == post.AuthorName;
    }

    private string? LocalCharacterName()
    {
        if (_playerManager.LocalEntity is not { } local)
            return null;

        return _entMan.GetComponentOrNull<MetaDataComponent>(local)?.EntityName;
    }

    private bool IsLiked(List<NetUserId> likedBy)
    {
        return _playerManager.LocalUser is { } user && likedBy.Contains(user);
    }

    private string LikeText(int count, bool liked)
    {
        return Loc.GetString(liked ? "internet-liked" : "internet-like", ("count", count));
    }

    private string PostingWarning()
    {
        if (_state is not { HasIdCard: true } || string.IsNullOrWhiteSpace(_state.IdCardName))
            return Loc.GetString("internet-popup-no-id");

        return Loc.GetString("internet-popup-id-mismatch");
    }

    private TextureButton? MakeImageButton(string? imageId, bool selected, Action<string?> onSelect)
    {
        if (imageId == null)
            return null;

        var button = new TextureButton
        {
            TextureNormal = FactionUi.GetEmblem(_sysMan, imageId),
            MinSize = new Vector2(26, 26),
            Scale = new Vector2(0.4f, 0.4f),
            Modulate = selected ? Color.White : new Color(1f, 1f, 1f, 0.5f),
            ToolTip = Loc.GetString("internet-image-tooltip", ("name", imageId)),
        };
        button.OnPressed += _ => onSelect(imageId);
        return button;
    }

    private Control MakeImageChoice(string? imageId, bool selected, Action<string?> onSelect)
    {
        if (imageId == null)
        {
            var none = new Button
            {
                Text = Loc.GetString("internet-image-none"),
                MinSize = new Vector2(0, 24),
                Modulate = selected ? Color.White : new Color(1f, 1f, 1f, 0.5f),
                ToolTip = Loc.GetString("internet-image-none-tooltip"),
            };
            none.OnPressed += _ => onSelect(null);
            return none;
        }

        return MakeImageButton(imageId, selected, onSelect)!;
    }

    private TextureRect MakeImage(string? imageId, int size)
    {
        return new TextureRect
        {
            Texture = imageId == null ? null : FactionUi.GetEmblem(_sysMan, imageId),
            MinSize = new Vector2(size, size),
            MaxSize = new Vector2(size, size),
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            Modulate = Accent,
            VerticalAlignment = VAlignment.Center,
        };
    }

    private static Label MakeEmptyLabel(string locKey)
    {
        return new Label
        {
            Text = Loc.GetString(locKey),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = Muted,
            Margin = new Thickness(8),
        };
    }

    private static StyleBoxFlat MakePanel(Color background, Color border, int thickness, int margin)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = background,
            BorderColor = border,
            BorderThickness = new Thickness(thickness),
            ContentMarginLeftOverride = margin,
            ContentMarginRightOverride = margin,
            ContentMarginTopOverride = margin,
            ContentMarginBottomOverride = margin,
        };
    }

    private static string TypeName(InternetPostType type)
    {
        return Loc.GetString($"internet-type-{type.ToString().ToLowerInvariant()}");
    }

    private static string Truncate(string value, int maxLength)
    {
        if (value.Length <= maxLength)
            return value;

        return value[..maxLength] + "...";
    }

    private static string FormatTime(long createdAt)
    {
        var seconds = DateTimeOffset.UtcNow.ToUnixTimeSeconds() - createdAt;

        if (seconds < 60)
            return Loc.GetString("internet-time-now");

        if (seconds < 3600)
            return Loc.GetString("internet-time-minutes", ("count", seconds / 60));

        if (seconds < 86400)
            return Loc.GetString("internet-time-hours", ("count", seconds / 3600));

        return Loc.GetString("internet-time-days", ("count", seconds / 86400));
    }

