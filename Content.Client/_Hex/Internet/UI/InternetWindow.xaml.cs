/// <summary>
///     Main window of the Internet PDA program. The window owns only presentation state; every
///     mutation is validated by the server, which then broadcasts a fresh <see cref="InternetUiState"/>.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class InternetWindow : PanelContainer
{
    private static readonly Color Accent = Color.FromHex("#45e0cf");
    private static readonly Color AccentSoft = Color.FromHex("#2fa59c");
    private static readonly Color TextColor = Color.FromHex("#d7fffb");
    private static readonly Color Muted = Color.FromHex("#7fb8b3");
    private static readonly Color PanelBackground = Color.FromHex("#0e2c2e");
    private static readonly Color PanelBackgroundAlt = Color.FromHex("#0a2224");
    private static readonly Color BorderColor = Color.FromHex("#1f6b67");
    private static readonly Color WarningColor = Color.FromHex("#ffb4a8");

    [Dependency] private readonly IEntityManager _entMan = default!;
    [Dependency] private readonly IEntitySystemManager _sysMan = default!;
    [Dependency] private readonly IPlayerManager _playerManager = default!;

    public event Action<InternetPostType, int, string, string, string?>? OnCreatePost;
    public event Action<int, string, string, string?>? OnEditPost;
    public event Action<int>? OnLikePost;
    public event Action<int, int, string>? OnAddComment;
    public event Action<int, int>? OnLikeComment;
    public event Action<int, string, string?>? OnSendChatMessage;
    public event Action? OnRefreshRequested;

    private InternetUiState? _state;
    private readonly List<InternetPostInfo> _posts = new();

    private InternetListTab _tab = InternetListTab.Feed;
    private ViewMode _view = ViewMode.List;
    private int _topicId;
    private int _postId;
    private int _editingPostId;
    private int _replyToCommentId;

    private ComposerMode _composerMode;
    private ViewMode _composerReturnView = ViewMode.List;
    private int _composerReturnPostId;
    private int _composerReturnTopicId;
    private InternetPostType _composerType = InternetPostType.Post;

    private string? _composerImage;
    private string? _chatImage;

    // Drafts are captured before a rebuild so incoming network updates do not erase what the
    // player is currently typing.
    private string _composerTitleDraft = string.Empty;
    private string _composerBodyDraft = string.Empty;
    private string _commentDraft = string.Empty;
    private string _chatDraft = string.Empty;

    private LineEdit? _composerTitleEdit;
    private TextEdit? _composerBodyEdit;
    private LineEdit? _commentInput;
    private LineEdit? _chatInput;

    public InternetWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        FeedTab.Text = Loc.GetString("internet-tab-feed");
        TopicsTab.Text = Loc.GetString("internet-tab-topics");
        ComposeButton.Text = "+";
        BackButton.Text = "<-";

        FeedTab.ToggleMode = true;
        TopicsTab.ToggleMode = true;

        FeedTab.OnPressed += _ => SwitchTab(InternetListTab.Feed);
        TopicsTab.OnPressed += _ => SwitchTab(InternetListTab.Topics);
        BackButton.OnPressed += _ => GoBack();
        ComposeButton.OnPressed += _ => OpenComposerForCreate();

        BuildView();
    }

    #region State

    public void UpdateState(InternetUiState state)
    {
        CaptureDrafts();

        _state = state;
        _posts.Clear();
        _posts.AddRange(state.Posts);

        if (_view == ViewMode.Post && FindPost(_postId) is not { Type: InternetPostType.Post })
        {
            _view = ViewMode.List;
            _postId = 0;
            _replyToCommentId = 0;
        }

        if (_view == ViewMode.Chat && FindPost(_postId) is not { Type: InternetPostType.Chat })
        {
            _view = ViewMode.List;
            _postId = 0;
        }

        if (_view == ViewMode.Composer &&
            _composerMode == ComposerMode.Edit &&
            FindPost(_editingPostId) == null)
        {
            CancelComposer();
            return;
        }

        if (_topicId != 0 && FindPost(_topicId) is not { Type: InternetPostType.Topic })
            _topicId = 0;

        BuildView();
    }

    private InternetPostInfo? FindPost(int id)
    {
        return _posts.FirstOrDefault(post => post.Id == id);
    }

    #endregion

    #region Navigation

    private void SwitchTab(InternetListTab tab)
    {
        CaptureDrafts();

        _tab = tab;
        _view = ViewMode.List;
        _topicId = 0;
        _postId = 0;
        _replyToCommentId = 0;
        _commentDraft = string.Empty;

        BuildView();
    }

    private void OpenPost(InternetPostInfo post)
    {
        CaptureDrafts();

        _replyToCommentId = 0;
        _commentDraft = string.Empty;

        switch (post.Type)
        {
            case InternetPostType.Topic:
                _topicId = post.Id;
                _view = ViewMode.List;
                break;
            case InternetPostType.Post:
                _postId = post.Id;
                _view = ViewMode.Post;
                break;
            case InternetPostType.Chat:
                _postId = post.Id;
                _view = ViewMode.Chat;
                break;
        }

        BuildView();
    }

    private void GoBack()
    {
        CaptureDrafts();

        switch (_view)
        {
            case ViewMode.Composer:
                CancelComposer();
                return;
            case ViewMode.Post:
            case ViewMode.Chat:
                var post = FindPost(_postId);
                _view = ViewMode.List;
                _topicId = post?.ParentId ?? 0;
                _postId = 0;
                _replyToCommentId = 0;
                _commentDraft = string.Empty;
                break;
            case ViewMode.List:
                if (_topicId == 0)
                    return;

                var topic = FindPost(_topicId);
                _topicId = topic?.ParentId ?? 0;
                break;
        }

        BuildView();
    }

    private void OpenComposerForCreate()
    {
        CaptureDrafts();

        _composerMode = ComposerMode.Create;
        _composerReturnView = ViewMode.List;
        _composerReturnPostId = 0;
        _composerReturnTopicId = _topicId;
        _editingPostId = 0;

        _composerType = _topicId == 0 && _tab == InternetListTab.Topics
            ? InternetPostType.Topic
            : InternetPostType.Post;

        _composerTitleDraft = string.Empty;
        _composerBodyDraft = string.Empty;
        _composerImage = null;
        _view = ViewMode.Composer;

        // Make sure the ID card check uses the card that is currently in the PDA.
        OnRefreshRequested?.Invoke();
        BuildView();
    }

    private void OpenComposerForEdit(InternetPostInfo post)
    {
        CaptureDrafts();

        _composerMode = ComposerMode.Edit;
        _composerReturnView = _view;
        _composerReturnPostId = _postId;
        _composerReturnTopicId = _topicId;
        _editingPostId = post.Id;
        _composerType = post.Type;
        _composerTitleDraft = post.Title;
        _composerBodyDraft = post.Body;
        _composerImage = post.ImageId;
        _view = ViewMode.Composer;

        BuildView();
    }

    private void CancelComposer()
    {
        _view = _composerReturnView;
        _postId = _composerReturnPostId;
        _topicId = _composerReturnTopicId;
        _editingPostId = 0;
        _composerTitleDraft = string.Empty;
        _composerBodyDraft = string.Empty;
        _composerImage = null;

        BuildView();
    }

    private void SubmitComposer()
    {
        CaptureDrafts();

        var title = _composerTitleDraft.Trim();
        var body = _composerBodyDraft.Trim();

        if (_composerMode == ComposerMode.Create)
            OnCreatePost?.Invoke(_composerType, _topicId, title, body, _composerImage);
        else
            OnEditPost?.Invoke(_editingPostId, title, body, _composerImage);

        _view = ViewMode.List;
        _editingPostId = 0;
        _composerTitleDraft = string.Empty;
        _composerBodyDraft = string.Empty;
        _composerImage = null;

        BuildView();
    }

    private void CaptureDrafts()
    {
        if (_view == ViewMode.Composer)
        {
            if (_composerTitleEdit != null)
                _composerTitleDraft = _composerTitleEdit.Text ?? string.Empty;

            if (_composerBodyEdit != null)
                _composerBodyDraft = _composerBodyEdit.Text ?? string.Empty;
        }
        else if (_view == ViewMode.Post && _commentInput != null)
        {
            _commentDraft = _commentInput.Text ?? string.Empty;
        }
        else if (_view == ViewMode.Chat && _chatInput != null)
        {
            _chatDraft = _chatInput.Text ?? string.Empty;
        }
    }

    #endregion

    #region Rendering

    private void BuildView()
    {
        _composerTitleEdit = null;
        _composerBodyEdit = null;
        _commentInput = null;
        _chatInput = null;

        ContentContainer.RemoveAllChildren();
        ContentScroll.SetScrollValue(Vector2.Zero);

        UpdateHeader();
        UpdateFooter();

        switch (_view)
        {
            case ViewMode.List:
                BuildList();
                break;
            case ViewMode.Post:
                BuildPost();
                break;
            case ViewMode.Chat:
                BuildChat();
                break;
            case ViewMode.Composer:
                BuildComposer();
                break;
        }
    }

    private void UpdateHeader()
    {
        var rootList = _view == ViewMode.List && _topicId == 0;

        BackButton.Visible = !rootList;
        FeedTab.Visible = rootList;
        TopicsTab.Visible = rootList;
        FeedTab.Pressed = _tab == InternetListTab.Feed;
        TopicsTab.Pressed = _tab == InternetListTab.Topics;

        switch (_view)
        {
            case ViewMode.List:
                HeaderTitle.Text = _topicId != 0
                    ? FindPost(_topicId)?.Title ?? Loc.GetString("internet-title")
                    : Loc.GetString("internet-title");
                break;
            case ViewMode.Post:
                HeaderTitle.Text = Loc.GetString("internet-post-title");
                break;
            case ViewMode.Chat:
                HeaderTitle.Text = FindPost(_postId)?.Title ?? Loc.GetString("internet-chat-title");
                break;
            case ViewMode.Composer:
                HeaderTitle.Text = Loc.GetString(_composerMode == ComposerMode.Edit
                    ? "internet-edit-post"
                    : "internet-new-entry");
                break;
        }

        PathLabel.Text = BuildPath();
    }

    private void UpdateFooter()
    {
        ComposeButton.Visible = _view == ViewMode.List;

        if (_state == null)
        {
            FooterLabel.Text = string.Empty;
            ComposeButton.ToolTip = Loc.GetString("internet-compose-tooltip");
            return;
        }

        if (!_state.HasIdCard || string.IsNullOrWhiteSpace(_state.IdCardName))
        {
            FooterLabel.Text = Loc.GetString("internet-footer-no-id");
            ComposeButton.ToolTip = Loc.GetString("internet-footer-no-id");
        }
        else if (_state.IdCardName != LocalCharacterName())
        {
            FooterLabel.Text = Loc.GetString("internet-footer-id-mismatch");
            ComposeButton.ToolTip = Loc.GetString("internet-footer-id-mismatch");
        }
        else
        {
            FooterLabel.Text = Loc.GetString("internet-footer-id", ("name", _state.IdCardName ?? string.Empty));
            ComposeButton.ToolTip = Loc.GetString("internet-compose-tooltip");
        }
    }

    private string BuildPath()
    {
        var parts = new List<string>();

        switch (_view)
        {
            case ViewMode.List:
                if (_topicId == 0)
                {
                    parts.Add(Loc.GetString("internet-title"));
                    parts.Add(Loc.GetString(_tab == InternetListTab.Feed
                        ? "internet-tab-feed"
                        : "internet-tab-topics"));
                    return string.Join(" > ", parts);
                }

                AddTopicPath(parts, _topicId);
                break;
            case ViewMode.Post:
            case ViewMode.Chat:
                if (FindPost(_postId) is { } post)
                {
                    AddTopicPath(parts, post.ParentId);
                    parts.Add(post.Title);
                    return string.Join(" > ", parts);
                }

                AddTopicPath(parts, 0);
                break;
            case ViewMode.Composer:
                AddTopicPath(parts, _topicId);
                parts.Add(Loc.GetString("internet-new-entry"));
                return string.Join(" > ", parts);
        }

        if (parts.Count == 0)
            AddTopicPath(parts, _topicId);

        return string.Join(" > ", parts);
    }

    private void AddTopicPath(List<string> parts, int topicId)
    {
        parts.Add(Loc.GetString("internet-title"));

        if (topicId == 0)
            return;

        var chain = new List<string>();
        var current = FindPost(topicId);
        var guard = 0;

        while (current != null && guard++ < 50)
        {
            chain.Add(current.Title);

            if (current.ParentId == 0)
                break;

            current = FindPost(current.ParentId);
        }

        chain.Reverse();
        parts.AddRange(chain);
    }

    private void BuildList()
    {
        var posts = GetVisiblePosts();

        if (posts.Count == 0)
        {
            ContentContainer.AddChild(MakeEmptyLabel(
                _topicId != 0
                    ? "internet-empty-topic"
                    : _tab == InternetListTab.Feed
                        ? "internet-empty-feed"
                        : "internet-empty-topics"));
            return;
        }

        foreach (var post in posts)
            ContentContainer.AddChild(BuildCard(post));
    }

    private List<InternetPostInfo> GetVisiblePosts()
    {
        IEnumerable<InternetPostInfo> query;

        if (_topicId != 0)
        {
            query = _posts.Where(post => post.ParentId == _topicId);
        }
        else if (_tab == InternetListTab.Feed)
        {
            query = _posts;
        }
        else
        {
            query = _posts.Where(post => post.Type == InternetPostType.Topic);
        }

        return query
            .OrderByDescending(post => post.CreatedAt)
            .ThenByDescending(post => post.Id)
            .ToList();
    }

    private Control BuildCard(InternetPostInfo post)
    {
        var button = new ContainerButton
        {
            HorizontalExpand = true,
            StyleBoxOverride = MakePanel(PanelBackground, BorderColor, 1, 8),
            ToolTip = Loc.GetString("internet-open-tooltip"),
        };
        button.OnPressed += _ => OpenPost(post);

        var root = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 3,
        };

        var titleRow = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 6,
        };

        titleRow.AddChild(new Label
        {
            Text = post.Title,
            StyleClasses = { "LabelKeyText" },
            FontColorOverride = Accent,
            HorizontalExpand = true,
            ClipText = true,
        });

        titleRow.AddChild(new Label
        {
            Text = TypeName(post.Type),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = Muted,
        });

        root.AddChild(titleRow);

        if (post.ImageId != null)
        {
            var imageRow = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                SeparationOverride = 6,
            };

            imageRow.AddChild(MakeImage(post.ImageId, 34));

            if (post.Type == InternetPostType.Post && !string.IsNullOrWhiteSpace(post.Body))
            {
                imageRow.AddChild(new Label
                {
                    Text = Truncate(post.Body.Replace('\n', ' '), 90),
                    FontColorOverride = TextColor,
                    HorizontalExpand = true,
                    ClipText = true,
                });
            }

            root.AddChild(imageRow);
        }
        else if (post.Type == InternetPostType.Post && !string.IsNullOrWhiteSpace(post.Body))
        {
            root.AddChild(new Label
            {
                Text = Truncate(post.Body.Replace('\n', ' '), 120),
                FontColorOverride = TextColor,
                HorizontalExpand = true,
                ClipText = true,
            });
        }

        if (post.Type == InternetPostType.Topic)
        {
            var childCount = _posts.Count(child => child.ParentId == post.Id);
            root.AddChild(new Label
            {
                Text = Loc.GetString("internet-topic-child-count", ("count", childCount)),
                StyleClasses = { "LabelSubText" },
                FontColorOverride = Muted,
            });
        }
        else if (post.Type == InternetPostType.Chat)
        {
            root.AddChild(new Label
            {
                Text = Loc.GetString("internet-chat-message-count", ("count", post.Messages.Count)),
                StyleClasses = { "LabelSubText" },
                FontColorOverride = Muted,
            });
        }

        var metaRow = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 6,
        };

        metaRow.AddChild(new Label
        {
            Text = Loc.GetString("internet-author", ("name", post.AuthorName)),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = Muted,
            HorizontalExpand = true,
            ClipText = true,
        });

        metaRow.AddChild(new Label
        {
            Text = FormatTime(post.CreatedAt) + (post.EditedAt != 0
                ? " · " + Loc.GetString("internet-edited")
                : string.Empty),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = Muted,
        });

        root.AddChild(metaRow);
        button.AddChild(root);
        return button;
    }

    private void BuildPost()
    {
        var post = FindPost(_postId);
        if (post == null)
        {
            _view = ViewMode.List;
            BuildView();
            return;
        }

        var panel = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = MakePanel(PanelBackground, BorderColor, 1, 8),
        };

        var root = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 5,
        };
        panel.AddChild(root);

        root.AddChild(new Label
        {
            Text = post.Title,
            StyleClasses = { "LabelBig" },
            FontColorOverride = Accent,
        });

        root.AddChild(new Label
        {
            Text = Loc.GetString("internet-author", ("name", post.AuthorName))
                   + " · " + FormatTime(post.CreatedAt)
                   + (post.EditedAt != 0 ? " · " + Loc.GetString("internet-edited") : string.Empty),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = Muted,
        });

        if (post.ImageId != null)
        {
            var image = MakeImage(post.ImageId, 120);
            image.HorizontalAlignment = HAlignment.Left;
            root.AddChild(image);
        }

        if (!string.IsNullOrWhiteSpace(post.Body))
        {
            var body = new RichTextLabel { HorizontalExpand = true };
            body.SetMessage(post.Body, defaultColor: TextColor);
            root.AddChild(body);
        }

        var actions = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
        };

        var like = new Button { Text = LikeText(post.LikedBy.Count, IsLiked(post.LikedBy)) };
        like.OnPressed += _ => OnLikePost?.Invoke(post.Id);
        actions.AddChild(like);

        if (CanEdit(post))
        {
            var edit = new Button { Text = Loc.GetString("internet-edit") };
            edit.OnPressed += _ => OpenComposerForEdit(post);
            actions.AddChild(edit);
        }

        root.AddChild(actions);
        ContentContainer.AddChild(panel);

        root.AddChild(new Label
        {
            Text = Loc.GetString("internet-comments-title", ("count", post.Comments.Count)),
            StyleClasses = { "LabelKeyText" },
            FontColorOverride = Accent,
            Margin = new Thickness(0, 6, 0, 0),
        });

        var topLevelComments = post.Comments
            .Where(comment => comment.ParentId == 0)
            .OrderByDescending(comment => comment.CreatedAt)
            .ThenByDescending(comment => comment.Id)
            .ToList();

        if (topLevelComments.Count == 0)
        {
            root.AddChild(MakeEmptyLabel("internet-no-comments"));
        }
        else
        {
            foreach (var comment in topLevelComments)
                root.AddChild(BuildComment(post, comment, 0));
        }

        BuildCommentInput(post, root);
    }

    private Control BuildComment(InternetPostInfo post, InternetCommentInfo comment, int depth)
    {
        var outer = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 2,
            Margin = new Thickness(depth * 12, 0, 0, 0),
        };

        var panel = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = MakePanel(PanelBackgroundAlt, BorderColor, 1, 6),
        };

        var root = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 2,
        };
        panel.AddChild(root);

        var meta = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 6,
        };

        meta.AddChild(new Label
        {
            Text = comment.AuthorName,
            FontColorOverride = AccentSoft,
            HorizontalExpand = true,
            ClipText = true,
        });

        meta.AddChild(new Label
        {
            Text = FormatTime(comment.CreatedAt),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = Muted,
        });

        root.AddChild(meta);

        var text = new RichTextLabel { HorizontalExpand = true };
        text.SetMessage(comment.Text, defaultColor: TextColor);
        root.AddChild(text);

        var actions = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 4,
        };

        var like = new Button
        {
            Text = LikeText(comment.LikedBy.Count, IsLiked(comment.LikedBy)),
            MinSize = new Vector2(0, 22),
        };
        like.OnPressed += _ => OnLikeComment?.Invoke(post.Id, comment.Id);
        actions.AddChild(like);

        var reply = new Button
        {
            Text = Loc.GetString("internet-reply"),
            MinSize = new Vector2(0, 22),
            Disabled = !CanPost,
        };
        reply.OnPressed += _ => StartReply(comment);
        actions.AddChild(reply);

        root.AddChild(actions);
        outer.AddChild(panel);

        foreach (var child in post.Comments
                     .Where(entry => entry.ParentId == comment.Id)
                     .OrderByDescending(entry => entry.CreatedAt)
                     .ThenByDescending(entry => entry.Id))
        {
            outer.AddChild(BuildComment(post, child, depth + 1));
        }

        return outer;
    }

    private void BuildCommentInput(InternetPostInfo post, BoxContainer root)
    {
        var inputPanel = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = MakePanel(PanelBackgroundAlt, BorderColor, 1, 6),
            Margin = new Thickness(0, 6, 0, 0),
        };

        var inputBox = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 3,
        };
        inputPanel.AddChild(inputBox);

        if (_replyToCommentId != 0)
        {
            var replying = post.Comments.FirstOrDefault(comment => comment.Id == _replyToCommentId);

            var replyRow = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                HorizontalExpand = true,
                SeparationOverride = 4,
            };

            replyRow.AddChild(new Label
            {
                Text = Loc.GetString("internet-replying-to", ("name", replying?.AuthorName ?? string.Empty)),
                StyleClasses = { "LabelSubText" },
                FontColorOverride = Muted,
                HorizontalExpand = true,
                ClipText = true,
            });

            var cancel = new Button { Text = Loc.GetString("internet-cancel") };
            cancel.OnPressed += _ =>
            {
                CaptureDrafts();
                _replyToCommentId = 0;
                BuildView();
            };
            replyRow.AddChild(cancel);

            inputBox.AddChild(replyRow);
        }

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 4,
        };

        _commentInput = new LineEdit
        {
            Text = _commentDraft,
            PlaceHolder = Loc.GetString("internet-comment-placeholder"),
            HorizontalExpand = true,
            MinSize = new Vector2(0, 26),
        };
        _commentInput.OnTextEntered += _ => SubmitComment(post.Id);

        var send = new Button
        {
            Text = Loc.GetString("internet-comment-send"),
            MinSize = new Vector2(0, 26),
            Disabled = !CanPost,
        };
        send.OnPressed += _ => SubmitComment(post.Id);

        row.AddChild(_commentInput);
        row.AddChild(send);
        inputBox.AddChild(row);
        root.AddChild(inputPanel);
    }

    private void StartReply(InternetCommentInfo comment)
    {
        CaptureDrafts();
        _replyToCommentId = comment.Id;
        _commentDraft = string.Empty;
        BuildView();
    }

    private void SubmitComment(int postId)
    {
        CaptureDrafts();

        var text = _commentDraft.Trim();
        if (text.Length == 0)
            return;

        OnAddComment?.Invoke(postId, _replyToCommentId, text);

        _commentDraft = string.Empty;
        _replyToCommentId = 0;
        BuildView();
    }

    private void BuildChat()
    {
        var post = FindPost(_postId);
        if (post == null || post.Type != InternetPostType.Chat)
        {
            _view = ViewMode.List;
            BuildView();
            return;
        }

        var root = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 4,
        };

        if (!string.IsNullOrWhiteSpace(post.Body))
        {
            var descriptionPanel = new PanelContainer
            {
                HorizontalExpand = true,
                PanelOverride = MakePanel(PanelBackground, BorderColor, 1, 6),
            };

            var description = new RichTextLabel { HorizontalExpand = true };
            description.SetMessage(post.Body, defaultColor: TextColor);
            descriptionPanel.AddChild(description);
            root.AddChild(descriptionPanel);
        }

        var messagesPanel = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = MakePanel(PanelBackground, BorderColor, 1, 6),
        };

        var messages = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 3,
        };
        messagesPanel.AddChild(messages);

        if (post.Messages.Count == 0)
        {
            messages.AddChild(MakeEmptyLabel("internet-no-messages"));
        }
        else
        {
            foreach (var message in post.Messages
                         .OrderBy(entry => entry.CreatedAt)
                         .ThenBy(entry => entry.Id))
            {
                messages.AddChild(BuildChatMessage(message));
            }
        }

        root.AddChild(messagesPanel);

        var picker = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 3,
        };

        picker.AddChild(new Label
        {
            Text = Loc.GetString("internet-image-label"),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = Muted,
            VerticalAlignment = VAlignment.Center,
        });

        picker.AddChild(MakeImageChoice(null, _chatImage == null, imageId =>
        {
            CaptureDrafts();
            _chatImage = imageId;
            BuildView();
        }));

        foreach (var imageId in InternetDefaults.Images)
        {
            var captured = imageId;
            picker.AddChild(MakeImageChoice(captured, _chatImage == captured, selected =>
            {
                CaptureDrafts();
                _chatImage = selected;
                BuildView();
            }));
        }

        root.AddChild(picker);

        var row = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 4,
        };

        _chatInput = new LineEdit
        {
            Text = _chatDraft,
            PlaceHolder = Loc.GetString("internet-chat-placeholder"),
            HorizontalExpand = true,
            MinSize = new Vector2(0, 26),
        };
        _chatInput.OnTextEntered += _ => SendChatMessage();

        var send = new Button
        {
            Text = Loc.GetString("internet-chat-send"),
            MinSize = new Vector2(0, 26),
            Disabled = !CanPost,
        };
        send.OnPressed += _ => SendChatMessage();

        row.AddChild(_chatInput);
        row.AddChild(send);
        root.AddChild(row);

        ContentContainer.AddChild(root);
    }

    private Control BuildChatMessage(InternetChatMessageInfo message)
    {
        var panel = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = MakePanel(PanelBackgroundAlt, BorderColor, 1, 6),
        };

        var root = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 2,
        };
        panel.AddChild(root);

        var meta = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 6,
        };

        meta.AddChild(new Label
        {
            Text = message.AuthorName,
            FontColorOverride = AccentSoft,
            HorizontalExpand = true,
            ClipText = true,
        });

        meta.AddChild(new Label
        {
            Text = FormatTime(message.CreatedAt),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = Muted,
        });

        root.AddChild(meta);

        if (!string.IsNullOrWhiteSpace(message.Text))
        {
            var text = new RichTextLabel { HorizontalExpand = true };
            text.SetMessage(message.Text, defaultColor: TextColor);
            root.AddChild(text);
        }

        if (message.ImageId != null)
        {
            var image = MakeImage(message.ImageId, 48);
            image.HorizontalAlignment = HAlignment.Left;
            root.AddChild(image);
        }

        return panel;
    }

    private void SendChatMessage()
    {
        CaptureDrafts();

        var text = _chatDraft.Trim();
        if (text.Length == 0 && _chatImage == null)
            return;

        OnSendChatMessage?.Invoke(_postId, text, _chatImage);

        _chatDraft = string.Empty;
        _chatImage = null;
        BuildView();
    }

    private void BuildComposer()
    {
        var panel = new PanelContainer
        {
            HorizontalExpand = true,
            PanelOverride = MakePanel(PanelBackground, BorderColor, 1, 8),
        };

        var root = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 4,
        };
        panel.AddChild(root);

        root.AddChild(new Label
        {
            Text = Loc.GetString("internet-compose-path", ("path", BuildPath())),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = Muted,
            ClipText = true,
        });

        if (_composerMode == ComposerMode.Create)
        {
            root.AddChild(new Label
            {
                Text = Loc.GetString("internet-type-select"),
                StyleClasses = { "LabelKeyText" },
                FontColorOverride = Accent,
            });

            var types = new BoxContainer
            {
                Orientation = BoxContainer.LayoutOrientation.Horizontal,
                SeparationOverride = 4,
            };

            foreach (var type in new[]
                     {
                         InternetPostType.Post,
                         InternetPostType.Topic,
                         InternetPostType.Chat,
                     })
            {
                var captured = type;
                var typeButton = new Button
                {
                    Text = TypeName(captured),
                    ToggleMode = true,
                    Pressed = _composerType == captured,
                    MinSize = new Vector2(0, 26),
                };
                typeButton.OnPressed += _ =>
                {
                    CaptureDrafts();
                    _composerType = captured;
                    BuildView();
                };
                types.AddChild(typeButton);
            }

            root.AddChild(types);
        }
        else
        {
            root.AddChild(new Label
            {
                Text = Loc.GetString("internet-editing-type", ("type", TypeName(_composerType))),
                StyleClasses = { "LabelSubText" },
                FontColorOverride = Muted,
            });
        }

        root.AddChild(new Label
        {
            Text = Loc.GetString("internet-title-label"),
            StyleClasses = { "LabelKeyText" },
            FontColorOverride = Accent,
        });

        _composerTitleEdit = new LineEdit
        {
            Text = _composerTitleDraft,
            PlaceHolder = Loc.GetString("internet-title-placeholder"),
            HorizontalExpand = true,
            MinSize = new Vector2(0, 26),
        };
        root.AddChild(_composerTitleEdit);

        root.AddChild(new Label
        {
            Text = Loc.GetString("internet-body-label"),
            StyleClasses = { "LabelKeyText" },
            FontColorOverride = Accent,
        });

        _composerBodyEdit = new TextEdit
        {
            Text = _composerBodyDraft,
            MinHeight = 70,
            HorizontalExpand = true,
        };
        root.AddChild(_composerBodyEdit);

        root.AddChild(new Label
        {
            Text = Loc.GetString("internet-image-label"),
            StyleClasses = { "LabelKeyText" },
            FontColorOverride = Accent,
        });

        var images = new GridContainer
        {
            Columns = 9,
            HorizontalExpand = true,
        };

        images.AddChild(MakeImageChoice(null, _composerImage == null, imageId =>
        {
            CaptureDrafts();
            _composerImage = imageId;
            BuildView();
        }));

        foreach (var imageId in InternetDefaults.Images)
        {
            var captured = imageId;
            images.AddChild(MakeImageChoice(captured, _composerImage == captured, selected =>
            {
                CaptureDrafts();
                _composerImage = selected;
                BuildView();
            }));
        }

        root.AddChild(images);

        if (!CanPost)
        {
            root.AddChild(new Label
            {
                Text = PostingWarning(),
                StyleClasses = { "LabelSubText" },
                FontColorOverride = WarningColor,
            });
        }

        var actions = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            SeparationOverride = 6,
            Margin = new Thickness(0, 4, 0, 0),
        };

        var submit = new Button
        {
            Text = Loc.GetString(_composerMode == ComposerMode.Create
                ? "internet-submit"
                : "internet-save"),
            MinSize = new Vector2(0, 28),
            Disabled = !CanPost,
        };
        submit.OnPressed += _ => SubmitComposer();

        var cancel = new Button
        {
            Text = Loc.GetString("internet-cancel"),
            MinSize = new Vector2(0, 28),
        };
        cancel.OnPressed += _ => CancelComposer();

        actions.AddChild(submit);
        actions.AddChild(cancel);
        root.AddChild(actions);

        ContentContainer.AddChild(panel);
    }

