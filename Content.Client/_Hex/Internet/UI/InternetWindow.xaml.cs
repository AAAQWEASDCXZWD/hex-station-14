    #region State

    public void UpdateState(InternetUiState state)
    {
        CaptureDrafts();

        var previousView = _view;
        var keepChatAtBottom = _view == ViewMode.Chat && IsScrollAtBottom();

        _state = state;
        ApplyTheme(state.Network, state.AdminMode && state.ViewerIsAdmin);

        DarknetAliasRow.Visible = state.Network == InternetNetwork.Darknet;
        DarknetAliasButton.Disabled = !state.HasIdCard;
        if (!DarknetAliasEdit.HasKeyboardFocus())
            DarknetAliasEdit.Text = state.DarknetAlias ?? string.Empty;

        _posts.Clear();
        _posts.AddRange(state.Posts);

        if (_view == ViewMode.Post && FindPost(_postId) is not { Type: InternetPostType.Post })
        {
            _view = ViewMode.List;
            _postId = 0;
            _replyToCommentId = 0;
        }

        if (_view == ViewMode.Chat && FindPost(_postId) is not { Type: InternetPostType.Chat })
        {
            _view = ViewMode.List;
            _postId = 0;
        }

        if (_view == ViewMode.Composer &&
            _composerMode == ComposerMode.Edit &&
            FindPost(_editingPostId) == null)
        {
            CancelComposer();
            return;
        }

        if (_topicId != 0 && FindPost(_topicId) is not { Type: InternetPostType.Topic })
            _topicId = 0;

        if (_view != previousView)
            BuildView(ScrollMode.Top);
        else
            BuildView(keepChatAtBottom ? ScrollMode.Bottom : ScrollMode.Preserve);
    }

    private InternetPostInfo? FindPost(int id)
    {
        return _posts.FirstOrDefault(post => post.Id == id);
    }

