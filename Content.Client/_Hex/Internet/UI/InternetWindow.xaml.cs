    private async void UploadImage(Action<byte[]?> onChanged)
    {
        var filters = new FileDialogFilters(new FileDialogFilters.Group("png", "jpg", "jpeg", "bmp", "gif", "webp"));
        await using var stream = await _fileDialog.OpenFile(filters, FileAccess.Read);
        if (stream == null || Disposed)
            return;

        try
        {
            var data = await Task.Run(() => EncodeImage(stream));
            if (Disposed)
                return;

            if (data.Length > InternetDefaults.MaxImageBytes)
            {
                _imageError = Loc.GetString("internet-image-too-large", ("max", InternetDefaults.MaxImageBytes / 1024));
                CaptureDrafts();
                BuildView(GetCurrentScrollMode());
                return;
            }

            _imageError = null;
            onChanged(data);
        }
        catch (Exception)
        {
            if (Disposed)
                return;

            _imageError = Loc.GetString("internet-image-error");
            CaptureDrafts();
            BuildView(GetCurrentScrollMode());
        }
    }

    /// <summary>
    ///     Decodes the uploaded file (PNG, JPEG, etc.), scales it down to the shared limit and
    ///     re-encodes it as PNG so the server only ever stores one predictable format.
    /// </summary>
    private static byte[] EncodeImage(Stream stream)
    {
        using var image = Image.Load<Rgba32>(stream);

        var maxDim = InternetDefaults.MaxImageDimension;
        if (image.Width > maxDim || image.Height > maxDim)
        {
            var ratio = Math.Min((float)maxDim / image.Width, (float)maxDim / image.Height);
            var width = Math.Max(1, (int)(image.Width * ratio));
            var height = Math.Max(1, (int)(image.Height * ratio));

            using var resized = new Image<Rgba32>(width, height);
            var sourcePixels = image.GetPixelSpan();
            var resizedPixels = resized.GetPixelSpan();

            for (var y = 0; y < height; y++)
            {
                var sourceY = y * image.Height / height;
                for (var x = 0; x < width; x++)
                {
                    var sourceX = x * image.Width / width;
                    resizedPixels[y * width + x] = sourcePixels[sourceY * image.Width + sourceX];
                }
            }

            using var resizedStream = new MemoryStream();
            resized.SaveAsPng(resizedStream);
            return resizedStream.ToArray();
        }

        using var pngStream = new MemoryStream();
        image.SaveAsPng(pngStream);
        return pngStream.ToArray();
    }

    private Texture? GetImageTexture(byte[]? imageData)
    {
        if (imageData == null)
            return null;

        var key = GetImageKey(imageData);
        if (_imageCache.TryGetValue(key, out var cached))
            return cached;

        // Keep the cache bounded even if a post's image is replaced many times.
        if (_imageCache.Count >= 64)
            _imageCache.Clear();

        var texture = FactionUi.LoadTextureFromBytes(imageData);
        _imageCache[key] = texture;
        return texture;
    }

    private static string GetImageKey(byte[] imageData)
    {
        // FNV-1a is used instead of a cryptographic hash because the sandbox blocks
        // System.Security.Cryptography types for content assemblies.
        var hash = 14695981039346656037UL;
        foreach (var value in imageData)
        {
            hash ^= value;
            hash *= 1099511628211UL;
        }

        return $"{imageData.Length}:{hash:X16}";
    }

    private TextureRect MakeImage(byte[]? imageData, int size)
    {
        return new TextureRect
        {
            Texture = GetImageTexture(imageData),
            MinSize = new Vector2(size, size),
            MaxSize = new Vector2(size, size),
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            Modulate = Color.White,
            VerticalAlignment = VAlignment.Center,
        };
    }

    private Label MakeEmptyLabel(string locKey)
    {
        return new Label
        {
            Text = Loc.GetString(locKey),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = Muted,
            Margin = new Thickness(8),
        };
    }

    private StyleBoxFlat MakePanel(Color background, Color border, int thickness, int margin)
    {
        return new StyleBoxFlat
        {
            BackgroundColor = background,
            BorderColor = border,
            BorderThickness = new Thickness(thickness),
            ContentMarginLeftOverride = margin,
            ContentMarginRightOverride = margin,
            ContentMarginTopOverride = margin,
            ContentMarginBottomOverride = margin,
        };
    }

    private static string TypeName(InternetPostType type)
    {
        return Loc.GetString($"internet-type-{type.ToString().ToLowerInvariant()}");
    }

    private static string Truncate(string value, int maxLength)
    {
        if (value.Length <= maxLength)
            return value;

        return value[..maxLength] + "...";
    }

    private static string FormatTime(long createdAt)
    {
        var seconds = DateTimeOffset.UtcNow.ToUnixTimeSeconds() - createdAt;

        if (seconds < 60)
            return Loc.GetString("internet-time-now");

        if (seconds < 3600)
            return Loc.GetString("internet-time-minutes", ("count", seconds / 60));

        if (seconds < 86400)
            return Loc.GetString("internet-time-hours", ("count", seconds / 3600));

        return Loc.GetString("internet-time-days", ("count", seconds / 86400));
    }

