using System.Collections.Generic;
using Content.Client.UserInterface.Controls;
using Content.Shared._Hex.Faction;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._Hex.Faction.UI;

/// <summary>
///     List of the characters that belong to the faction.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class FactionMembersWindow : FancyWindow
{
    public FactionMembersWindow()
    {
        RobustXamlLoader.Load(this);
        Title = Loc.GetString("faction-members-title");
    }

    public void UpdateState(FactionComputerUiState state)
    {
        MembersContainer.RemoveAllChildren();

        if (state.Members.Count == 0)
        {
            MembersContainer.AddChild(new Label
            {
                Text = Loc.GetString("faction-members-empty"),
                FontColorOverride = Color.FromHex("#94a3b8"),
            });
            return;
        }

        foreach (var member in state.Members)
        {
            MembersContainer.AddChild(CreateRow(member));
        }
    }

    private static Control CreateRow(FactionMemberInfo member)
    {
        var row = new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 2),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#141a22"),
                BorderColor = Color.FromHex("#1f2a37"),
                BorderThickness = new Thickness(1),
                ContentMarginLeftOverride = 8,
                ContentMarginRightOverride = 8,
                ContentMarginTopOverride = 4,
                ContentMarginBottomOverride = 4,
            },
        };

        var box = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };

        box.AddChild(new Label
        {
            Text = member.CharacterName,
            HorizontalExpand = true,
            ClipText = true,
        });

        var roleColor = member.Role switch
        {
            FactionRole.Leader => Color.FromHex("#facc15"),
            FactionRole.Officer => Color.FromHex("#60a5fa"),
            _ => Color.FromHex("#94a3b8"),
        };

        box.AddChild(new Label
        {
            Text = Loc.GetString(member.Role switch
            {
                FactionRole.Leader => "faction-role-leader",
                FactionRole.Officer => "faction-role-officer",
                _ => "faction-role-member",
            }),
            FontColorOverride = roleColor,
        });

        row.AddChild(box);
        return row;
    }
}
