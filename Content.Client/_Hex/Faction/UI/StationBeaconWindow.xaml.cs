using System;
using Content.Client.UserInterface.Controls;
using Content.Shared._Hex.Faction;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Hex.Faction.UI;

/// <summary>
///     Configuration window for a faction station beacon.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class StationBeaconWindow : FancyWindow
{
    public event Action<string>? OnUpdateRequested;

    public StationBeaconWindow()
    {
        RobustXamlLoader.Load(this);
        Title = Loc.GetString("station-beacon-window-title");

        UpdateButton.OnPressed += _ => OnUpdateRequested?.Invoke(LabelEdit.Text.Trim());
    }

    public void UpdateState(StationBeaconUiState state)
    {
        LabelEdit.Text = state.Label;
        FactionLabel.Text = state.FactionName;
        FactionLabel.Visible = !string.IsNullOrWhiteSpace(state.FactionName);

        if (!state.HasClaim)
        {
            StatusLabel.Text = Loc.GetString("station-beacon-status-unclaimed");
            return;
        }

        StatusLabel.Text = Loc.GetString(
            state.Active ? "station-beacon-status-active" : "station-beacon-status-inactive",
            ("q", state.HexQ),
            ("r", state.HexR));
    }
}
