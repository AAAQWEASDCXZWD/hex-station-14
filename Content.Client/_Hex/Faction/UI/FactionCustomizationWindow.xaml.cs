using System;
using System.Collections.Generic;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._Hex.Faction;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.Utility;

namespace Content.Client._Hex.Faction.UI;

/// <summary>
///     Faction customization window, laid out like a social media profile.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class FactionCustomizationWindow : FancyWindow
{
    [Dependency] private readonly IEntitySystemManager _sysMan = default!;

    public event Action<string, string, string, string>? OnSaveRequested;

    private static readonly Vector2 SwatchSize = new(30, 30);

    private readonly List<(string Id, PanelContainer Panel)> _colorSwatches = new();
    private readonly List<(string Id, PanelContainer Panel, TextureButton Button)> _photoSwatches = new();

    private string _color = FactionDefaults.DefaultColor;
    private string _photo = FactionDefaults.DefaultPhoto;
    private bool _updating;

    public FactionCustomizationWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        Title = Loc.GetString("faction-customization-title");

        SaveButton.OnPressed += _ => Save();
        NameEdit.OnTextChanged += _ => UpdatePreview();
        DescriptionEdit.OnTextChanged += _ => UpdatePreview();

        BuildColorSwatches();
        BuildPhotoSwatches();
    }

    public void UpdateState(FactionComputerUiState state)
    {
        _updating = true;
        NameEdit.Text = state.FactionName;
        DescriptionEdit.TextRope = new Rope.Leaf(state.Description);
        _color = FactionDefaults.IsValidColor(state.ColorHex) ? state.ColorHex : FactionDefaults.DefaultColor;
        _photo = FactionDefaults.IsValidPhoto(state.PhotoId) ? state.PhotoId : FactionDefaults.DefaultPhoto;
        _updating = false;

        RefreshSwatches();
        UpdatePreview();
    }

    private void Save()
    {
        var name = NameEdit.Text.Trim();
        if (name.Length == 0)
            return;

        var description = Rope.Collapse(DescriptionEdit.TextRope).Trim();
        OnSaveRequested?.Invoke(name, description, _color, _photo);
    }

    private void BuildColorSwatches()
    {
        foreach (var hex in FactionDefaults.Colors)
        {
            var panel = CreateSwatchPanel();
            var button = new TextureButton
            {
                TextureNormal = Texture.White,
                Modulate = FactionUi.GetColor(hex),
                MinSize = SwatchSize,
                ToolTip = hex,
            };

            var value = hex;
            button.OnPressed += _ =>
            {
                _color = value;
                RefreshSwatches();
                UpdatePreview();
            };

            panel.AddChild(button);
            ColorGrid.AddChild(panel);
            _colorSwatches.Add((hex, panel));
        }
    }

    private void BuildPhotoSwatches()
    {
        foreach (var photo in FactionDefaults.Photos)
        {
            var panel = CreateSwatchPanel();
            var button = new TextureButton
            {
                TextureNormal = FactionUi.GetEmblem(_sysMan, photo),
                Modulate = FactionUi.GetColor(_color),
                MinSize = SwatchSize,
                ToolTip = photo,
            };

            var value = photo;
            button.OnPressed += _ =>
            {
                _photo = value;
                RefreshSwatches();
                UpdatePreview();
            };

            panel.AddChild(button);
            PhotoGrid.AddChild(panel);
            _photoSwatches.Add((photo, panel, button));
        }
    }

    private static PanelContainer CreateSwatchPanel()
    {
        return new PanelContainer
        {
            MinSize = SwatchSize + new Vector2(8, 8),
            PanelOverride = FactionUi.CreateSwatchStyle(false),
        };
    }

    private void RefreshSwatches()
    {
        foreach (var (id, panel) in _colorSwatches)
        {
            panel.PanelOverride = FactionUi.CreateSwatchStyle(id == _color);
        }

        var color = FactionUi.GetColor(_color);
        foreach (var (id, panel, button) in _photoSwatches)
        {
            panel.PanelOverride = FactionUi.CreateSwatchStyle(id == _photo);
            button.Modulate = color;
        }
    }

    private void UpdatePreview()
    {
        if (_updating)
            return;

        var color = FactionUi.GetColor(_color);
        PreviewPanel.PanelOverride = FactionUi.CreateHeaderStyle(color);

        PhotoRect.Texture = FactionUi.GetEmblem(_sysMan, _photo);
        PhotoRect.Modulate = color;

        var name = NameEdit.Text.Trim();
        NamePreviewLabel.Text = name.Length == 0
            ? Loc.GetString("faction-customization-name-placeholder")
            : name;
        NamePreviewLabel.FontColorOverride = color;

        var description = Rope.Collapse(DescriptionEdit.TextRope).Trim();
        DescriptionPreviewLabel.Text = description.Length == 0
            ? Loc.GetString("faction-customization-description-placeholder")
            : description;
    }
}
