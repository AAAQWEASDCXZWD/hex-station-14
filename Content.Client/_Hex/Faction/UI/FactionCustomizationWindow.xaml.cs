using System;
using System.Collections.Generic;
using System.IO;
using System.Numerics;
using System.Threading.Tasks;
using Content.Client.UserInterface.Controls;
using Content.Shared._Hex.Faction;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Client.Utility;
using Robust.Shared.GameObjects;
using Robust.Shared.Utility;
using SixLabors.ImageSharp;
using SixLabors.ImageSharp.PixelFormats;
using Color = Robust.Shared.Maths.Color;

namespace Content.Client._Hex.Faction.UI;

/// <summary>
///     Faction customization window with color picker, RGB input, photo selection, and custom photo upload.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class FactionCustomizationWindow : FancyWindow
{
    [Dependency] private readonly IEntitySystemManager _sysMan = default!;
    [Dependency] private readonly IFileDialogManager _fileDialog = default!;

    public event Action<string, string, string, string, byte[]?>? OnSaveRequested;

    private static readonly Vector2 SwatchSize = new(30, 30);

    private readonly List<(string Id, PanelContainer Panel)> _colorSwatches = new();
    private readonly List<(string Id, PanelContainer Panel, TextureButton Button)> _photoSwatches = new();

    private string _color = FactionDefaults.DefaultColor;
    private string _photo = FactionDefaults.DefaultPhoto;
    private byte[]? _customPhotoData;
    private bool _updating;

    public FactionCustomizationWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        Title = Loc.GetString("faction-customization-title");

        SaveButton.OnPressed += _ => Save();
        NameEdit.OnTextChanged += _ => UpdatePreview();
        DescriptionEdit.OnTextChanged += _ => UpdatePreview();
        ColorHexEdit.OnTextChanged += _ => OnColorHexChanged();
        UploadPhotoButton.OnPressed += _ => OnUploadPhoto();

        BuildColorSwatches();
        BuildPhotoSwatches();
    }

    public void UpdateState(FactionComputerUiState state)
    {
        _updating = true;
        NameEdit.Text = state.FactionName;
        DescriptionEdit.TextRope = new Rope.Leaf(state.Description);
        _color = FactionDefaults.IsValidColor(state.ColorHex) ? state.ColorHex : FactionDefaults.DefaultColor;
        _photo = FactionDefaults.IsValidPhoto(state.PhotoId) ? state.PhotoId : FactionDefaults.DefaultPhoto;
        _customPhotoData = state.CustomPhotoData;
        ColorHexEdit.Text = _color;
        _updating = false;

        if (_customPhotoData is { Length: > 0 })
        {
            PhotoStatusLabel.Text = Loc.GetString("faction-customization-photo-custom");
            PhotoStatusLabel.Visible = true;
        }
        else
        {
            PhotoStatusLabel.Visible = false;
        }

        RefreshSwatches();
        UpdatePreview();
    }

    private void Save()
    {
        var name = NameEdit.Text.Trim();
        if (name.Length == 0)
            return;

        var description = Rope.Collapse(DescriptionEdit.TextRope).Trim();
        OnSaveRequested?.Invoke(name, description, _color, _photo, _customPhotoData);
    }

    private void OnColorHexChanged()
    {
        if (_updating)
            return;

        var text = ColorHexEdit.Text.Trim();
        if (!text.StartsWith('#'))
            text = "#" + text;

        if (Color.TryFromHex(text) == null)
            return;

        _color = text;
        RefreshSwatches();
        UpdatePreview();
    }

    private async void OnUploadPhoto()
    {
        var filters = new FileDialogFilters(new FileDialogFilters.Group("png", "jpg", "jpeg"));
        await using var stream = await _fileDialog.OpenFile(filters, FileAccess.Read);
        if (stream == null)
            return;

        try
        {
            // Decoding and encoding can take a moment for large photos, so keep it off the UI thread.
            var data = await Task.Run(() => EncodeCustomPhoto(stream));

            if (data.Length > FactionDefaults.MaxCustomPhotoBytes)
            {
                PhotoStatusLabel.Text = Loc.GetString("faction-customization-photo-too-large");
                PhotoStatusLabel.Visible = true;
                return;
            }

            _customPhotoData = data;
            PhotoStatusLabel.Text = Loc.GetString("faction-customization-photo-uploaded");
            PhotoStatusLabel.Visible = true;
            UpdatePreview();
        }
        catch (Exception)
        {
            PhotoStatusLabel.Text = Loc.GetString("faction-customization-photo-error");
            PhotoStatusLabel.Visible = true;
        }
    }

    /// <summary>
    ///     Decodes an uploaded photo, scales it down to fit the custom photo limit,
    ///     and re-encodes it as PNG.
    /// </summary>
    private static byte[] EncodeCustomPhoto(Stream stream)
    {
        using var image = Image.Load<Rgba32>(stream);

        var maxDim = FactionDefaults.MaxCustomPhotoDimension;
        if (image.Width > maxDim || image.Height > maxDim)
        {
            var ratio = Math.Min((float) maxDim / image.Width, (float) maxDim / image.Height);
            var width = Math.Max(1, (int) (image.Width * ratio));
            var height = Math.Max(1, (int) (image.Height * ratio));

            using var resized = new Image<Rgba32>(width, height);
            var sourcePixels = image.GetPixelSpan();
            var resizedPixels = resized.GetPixelSpan();

            for (var y = 0; y < height; y++)
            {
                var sourceY = y * image.Height / height;
                for (var x = 0; x < width; x++)
                {
                    var sourceX = x * image.Width / width;
                    resizedPixels[y * width + x] = sourcePixels[sourceY * image.Width + sourceX];
                }
            }

            using var resizedStream = new MemoryStream();
            resized.SaveAsPng(resizedStream);
            return resizedStream.ToArray();
        }

        using var pngStream = new MemoryStream();
        image.SaveAsPng(pngStream);
        return pngStream.ToArray();
    }

    private void BuildColorSwatches()
    {
        foreach (var hex in FactionDefaults.Colors)
        {
            var panel = CreateSwatchPanel();
            var button = new TextureButton
            {
                TextureNormal = Texture.White,
                Modulate = FactionUi.GetColor(hex),
                MinSize = SwatchSize,
                ToolTip = hex,
            };

            var value = hex;
            button.OnPressed += _ =>
            {
                _color = value;
                ColorHexEdit.Text = value;
                RefreshSwatches();
                UpdatePreview();
            };

            panel.AddChild(button);
            ColorGrid.AddChild(panel);
            _colorSwatches.Add((hex, panel));
        }
    }

    private void BuildPhotoSwatches()
    {
        foreach (var photo in FactionDefaults.Photos)
        {
            var panel = CreateSwatchPanel();
            var button = new TextureButton
            {
                TextureNormal = FactionUi.GetEmblem(_sysMan, photo),
                Modulate = FactionUi.GetColor(_color),
                MinSize = SwatchSize,
                ToolTip = photo,
            };

            var value = photo;
            button.OnPressed += _ =>
            {
                _photo = value;
                _customPhotoData = null; // Clear custom photo when selecting a preset.
                PhotoStatusLabel.Visible = false;
                RefreshSwatches();
                UpdatePreview();
            };

            panel.AddChild(button);
            PhotoGrid.AddChild(panel);
            _photoSwatches.Add((photo, panel, button));
        }
    }

    private static PanelContainer CreateSwatchPanel()
    {
        return new PanelContainer
        {
            MinSize = SwatchSize + new Vector2(8, 8),
            PanelOverride = FactionUi.CreateSwatchStyle(false),
        };
    }

    private void RefreshSwatches()
    {
        foreach (var (id, panel) in _colorSwatches)
        {
            panel.PanelOverride = FactionUi.CreateSwatchStyle(id == _color);
        }

        var color = FactionUi.GetColor(_color);
        foreach (var (id, panel, button) in _photoSwatches)
        {
            panel.PanelOverride = FactionUi.CreateSwatchStyle(id == _photo && _customPhotoData == null);
            button.Modulate = color;
        }
    }

    private void UpdatePreview()
    {
        if (_updating)
            return;

        var color = FactionUi.GetColor(_color);
        PreviewPanel.PanelOverride = FactionUi.CreateHeaderStyle(color);

        // Custom photo takes priority over preset emblem.
        var customTex = FactionUi.LoadTextureFromBytes(_customPhotoData);
        PhotoRect.Texture = customTex ?? FactionUi.GetEmblem(_sysMan, _photo);
        PhotoRect.Modulate = customTex != null ? Color.White : color;

        var name = NameEdit.Text.Trim();
        NamePreviewLabel.Text = name.Length == 0
            ? Loc.GetString("faction-customization-name-placeholder")
            : name;
        NamePreviewLabel.FontColorOverride = color;

        var description = Rope.Collapse(DescriptionEdit.TextRope).Trim();
        DescriptionPreviewLabel.Text = description.Length == 0
            ? Loc.GetString("faction-customization-description-placeholder")
            : description;
    }
}
