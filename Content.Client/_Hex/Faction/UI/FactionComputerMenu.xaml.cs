using System;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._Hex.Faction;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.Player;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.Maths;

namespace Content.Client._Hex.Faction.UI;

/// <summary>
///     Main faction terminal window: registration until the terminal is claimed, then the faction profile.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class FactionComputerMenu : FancyWindow
{
    [Dependency] private readonly IPlayerManager _playerManager = default!;
    [Dependency] private readonly IEntitySystemManager _sysMan = default!;

    public event Action<string>? OnCreateRequested;
    public event Action<string>? OnLinkRequested;
    public event Action? OnIdCardPressed;
    public event Action? OnOpenCustomization;
    public event Action? OnOpenMembers;
    public event Action? OnOpenProgress;

    public FactionComputerMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        Title = Loc.GetString("faction-computer-menu-title");

        IdCardButton.OnPressed += _ => OnIdCardPressed?.Invoke();
        CreateButton.OnPressed += _ => OnCreateRequested?.Invoke(NameEdit.Text.Trim());
        CustomizationButton.OnPressed += _ => OnOpenCustomization?.Invoke();
        MembersButton.OnPressed += _ => OnOpenMembers?.Invoke();
        ProgressButton.OnPressed += _ => OnOpenProgress?.Invoke();
    }

    public void UpdateState(FactionComputerUiState state)
    {
        RegisterContainer.Visible = !state.Registered;
        ProfileContainer.Visible = state.Registered;

        if (FactionDetailContainer != null)
            FactionDetailContainer.Visible = false;

        if (!state.Registered)
        {
            UpdateRegistration(state);
            return;
        }

        var color = FactionUi.GetColor(state.ColorHex);
        HeaderPanel.PanelOverride = FactionUi.CreateHeaderStyle(color);

        // Custom photo takes priority over preset emblem.
        var customTex = FactionUi.LoadTextureFromBytes(state.CustomPhotoData);
        PhotoRect.Texture = customTex ?? FactionUi.GetEmblem(_sysMan, state.PhotoId);
        PhotoRect.Modulate = customTex != null ? Color.White : color;

        FactionNameLabel.Text = state.FactionName;
        FactionNameLabel.FontColorOverride = color;
        DescriptionLabel.Text = string.IsNullOrWhiteSpace(state.Description)
            ? Loc.GetString("faction-computer-no-description")
            : state.Description;

        if (BeaconCountLabel != null)
            BeaconCountLabel.Text = Loc.GetString("faction-computer-beacon-count", ("count", state.BeaconCount));

        var isLeader = _playerManager.LocalUser is { } user && user == state.OwnerUserId;
        CustomizationButton.Disabled = !isLeader;
        OwnerNote.Visible = !isLeader;
    }

    private void UpdateRegistration(FactionComputerUiState state)
    {
        IdCardButton.Text = Loc.GetString(state.HasIdCard
            ? "faction-computer-id-eject"
            : "faction-computer-id-insert");
        IdCardStatus.Text = state.HasIdCard
            ? Loc.GetString("faction-computer-id-status", ("name", state.IdCardName ?? string.Empty))
            : Loc.GetString("faction-computer-id-empty");
        CreateButton.Disabled = !state.HasIdCard;

        FactionListContainer.RemoveAllChildren();

        var localUser = _playerManager.LocalUser;
        foreach (var listing in state.AvailableFactions)
        {
            var canLink = localUser is { } user && listing.MemberUserIds.Contains(user);
            FactionListContainer.AddChild(CreateFactionRow(listing, canLink));
        }

        NoFactionsLabel.Visible = state.AvailableFactions.Count == 0;
    }

    private Control CreateFactionRow(FactionListingInfo listing, bool canLink)
    {
        var row = new PanelContainer
        {
            HorizontalExpand = true,
            Margin = new Thickness(0, 2),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Color.FromHex("#141a22"),
                BorderColor = Color.FromHex("#1f2a37"),
                BorderThickness = new Thickness(1),
                ContentMarginLeftOverride = 8,
                ContentMarginRightOverride = 8,
                ContentMarginTopOverride = 5,
                ContentMarginBottomOverride = 5,
            },
        };

        var color = FactionUi.GetColor(listing.ColorHex);
        var outer = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            SeparationOverride = 8,
        };

        outer.AddChild(new TextureRect
        {
            Texture = FactionUi.GetEmblem(_sysMan, listing.PhotoId),
            Modulate = color,
            MinSize = new Vector2(24, 24),
            Stretch = TextureRect.StretchMode.KeepAspectCentered,
            VerticalAlignment = VAlignment.Center,
        });

        var infoBox = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            SeparationOverride = 1,
            VerticalAlignment = VAlignment.Center,
        };
        infoBox.AddChild(new Label
        {
            Text = listing.Name,
            FontColorOverride = Color.FromHex("#e2e8f0"),
            ClipText = true,
            HorizontalExpand = true,
        });
        infoBox.AddChild(new Label
        {
            Text = Loc.GetString("faction-computer-link-leader", ("name", listing.LeaderName)),
            StyleClasses = { "LabelSubText" },
            FontColorOverride = Color.FromHex("#94a3b8"),
            ClipText = true,
        });
        outer.AddChild(infoBox);

        // Buttons stacked vertically so they don't overflow the narrow panel.
        var buttonBox = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            SeparationOverride = 3,
            VerticalAlignment = VAlignment.Center,
        };

        var viewButton = new Button
        {
            Text = Loc.GetString("faction-computer-view"),
            MinSize = new Vector2(50, 24),
        };
        viewButton.OnPressed += _ => ShowFactionDetail(listing);

        var linkButton = new Button
        {
            Text = Loc.GetString("faction-computer-link"),
            Disabled = !canLink,
            MinSize = new Vector2(50, 24),
            ToolTip = canLink ? null : Loc.GetString("faction-computer-link-not-member"),
        };

        var factionId = listing.Id;
        linkButton.OnPressed += _ => OnLinkRequested?.Invoke(factionId);

        buttonBox.AddChild(viewButton);
        buttonBox.AddChild(linkButton);
        outer.AddChild(buttonBox);
        row.AddChild(outer);
        return row;
    }

    private void ShowFactionDetail(FactionListingInfo listing)
    {
        if (FactionDetailContainer == null)
            return;

        FactionDetailContainer.Visible = true;

        if (DetailPhotoRect != null)
            DetailPhotoRect.Texture = FactionUi.GetEmblem(_sysMan, listing.PhotoId);

        if (DetailNameLabel != null)
        {
            DetailNameLabel.Text = listing.Name;
            DetailNameLabel.FontColorOverride = FactionUi.GetColor(listing.ColorHex);
        }

        if (DetailDescriptionLabel != null)
            DetailDescriptionLabel.Text = string.IsNullOrWhiteSpace(listing.Description)
                ? Loc.GetString("faction-computer-no-description")
                : listing.Description;

        if (DetailLeaderLabel != null)
            DetailLeaderLabel.Text = Loc.GetString("faction-computer-detail-leader", ("name", listing.LeaderName));

        if (DetailMembersLabel != null)
            DetailMembersLabel.Text = Loc.GetString("faction-computer-detail-members", ("count", listing.Members.Count));

        if (DetailBeaconCountLabel != null)
            DetailBeaconCountLabel.Text = Loc.GetString("faction-computer-beacon-count", ("count", listing.BeaconCount));

        if (DetailMembersContainer != null)
        {
            DetailMembersContainer.RemoveAllChildren();
            foreach (var member in listing.Members)
            {
                var memberLabel = new Label
                {
                    Text = $"{member.CharacterName} — {Loc.GetString($"faction-role-{member.Role.ToString().ToLowerInvariant()}")}",
                    FontColorOverride = Color.FromHex("#cbd5e1"),
                };
                memberLabel.StyleClasses.Add("LabelSubText");
                DetailMembersContainer.AddChild(memberLabel);
            }
        }
    }
}
