using System.Linq;
using Content.Client.Shuttles.UI;
using Content.Client.UserInterface.Controls;
using Content.Shared._Hex.FireControl;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client._Hex.FireControl.UI;

[GenerateTypedNameReferences]
public sealed partial class FireControlWindow : FancyWindow
{
    /// <summary>
    /// Radar control that sends the fire coordinates to the server while the mouse is held.
    /// </summary>
    public ShuttleNavControl Radar => NavRadar;

    /// <summary>
    /// Raised when the player requests a server re-scan.
    /// </summary>
    public event Action? OnServerRefresh;

    private readonly Dictionary<NetEntity, Button> _weapons = new();
    private FireControlConsoleBoundInterfaceState? _state;

    public FireControlWindow()
    {
        RobustXamlLoader.Load(this);

        RefreshButton.OnPressed += _ => OnServerRefresh?.Invoke();
        SelectAllButton.OnPressed += _ => SetAllPressed(true);
        UnselectAllButton.OnPressed += _ => SetAllPressed(false);
    }

    public List<NetEntity> GetSelectedWeapons()
    {
        var selected = new List<NetEntity>();

        foreach (var (netEntity, button) in _weapons)
        {
            if (button.Pressed)
                selected.Add(netEntity);
        }

        return selected;
    }

    private void SetAllPressed(bool pressed)
    {
        foreach (var button in _weapons.Values)
            button.Pressed = pressed;

        UpdateAllWeaponTexts();
        UpdateSelectionVisuals();
    }

    public void UpdateStatus(FireControlConsoleBoundInterfaceState state)
    {
        _state = state;

        NavRadar.UpdateState(state.NavState);
        NavRadar.SetFireControlWeapons(state.FireControllables);

        ServerStatus.Text = state.Connected
            ? Loc.GetString("gunnery-window-connected")
            : Loc.GetString("gunnery-window-disconnected");
        ServerStatus.FontColorOverride = state.Connected ? Color.Green : Color.Red;

        UpdateWeapons(state.FireControllables);
        UpdateSelectionVisuals();
    }

    private void UpdateSelectionVisuals()
    {
        NavRadar.SetFireControlSelection(GetSelectedWeapons());
    }

    private void UpdateWeapons(FireControllableEntry[] entries)
    {
        entries ??= Array.Empty<FireControllableEntry>();
        var seen = new HashSet<NetEntity>();
        foreach (var entry in entries)
        {
            seen.Add(entry.NetEntity);

            if (_weapons.TryGetValue(entry.NetEntity, out var existing))
            {
                UpdateWeaponText(existing, entry);
                continue;
            }

            var button = new Button
            {
                ToggleMode = true,
                HorizontalExpand = true,
                StyleClasses = { "ButtonSquare" },
            };

            button.OnToggled += _ =>
            {
                UpdateAllWeaponTexts();
                UpdateSelectionVisuals();
            };

            ControllablesBox.AddChild(button);
            _weapons.Add(entry.NetEntity, button);
            UpdateWeaponText(button, entry);
        }

        foreach (var netEntity in _weapons.Keys.ToList())
        {
            if (seen.Contains(netEntity))
                continue;

            ControllablesBox.RemoveChild(_weapons[netEntity]);
            _weapons.Remove(netEntity);
        }

        SelectAllButton.Disabled = _weapons.Count == 0;
        UnselectAllButton.Disabled = _weapons.Count == 0;
    }

    private static void UpdateWeaponText(Button button, FireControllableEntry entry)
    {
        button.Text = button.Pressed && entry.HasManualReload && entry.HasAmmoCount
            ? Loc.GetString("gunnery-gun-select-ammo", ("name", entry.Name), ("ammo", entry.AmmoCount))
            : Loc.GetString("gunnery-gun-select", ("name", entry.Name));

        button.ModulateSelfOverride = entry.HasManualReload && entry.HasAmmoCount && entry.AmmoCount == 0
            ? Color.Red
            : null;
    }

    private void UpdateAllWeaponTexts()
    {
        if (_state == null)
            return;

        foreach (var entry in _state.FireControllables)
        {
            if (_weapons.TryGetValue(entry.NetEntity, out var button))
                UpdateWeaponText(button, entry);
        }
    }
}
