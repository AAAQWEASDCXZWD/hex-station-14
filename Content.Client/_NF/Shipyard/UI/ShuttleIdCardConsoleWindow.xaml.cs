using System.Linq;
using Content.Client.Access.UI;
using Content.Shared._NF.Shipyard.BUI;
using Content.Shared.Access;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;

namespace Content.Client._NF.Shipyard.UI;

[GenerateTypedNameReferences]
public sealed partial class ShuttleIdCardConsoleWindow : DefaultWindow
{
    private readonly ShuttleIdCardConsoleBoundUserInterface _owner;
    private readonly AccessLevelControl _accessButtons = new();
    private readonly List<NetEntity> _availableShuttles = new();
    private NetEntity? _selectedShuttle;

    public ShuttleIdCardConsoleWindow(
        ShuttleIdCardConsoleBoundUserInterface owner,
        IPrototypeManager prototypeManager,
        List<ProtoId<AccessLevelPrototype>> accessLevels)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        _owner = owner;

        _accessButtons.Populate(accessLevels, prototypeManager);
        AccessLevelControlContainer.AddChild(_accessButtons);

        ShuttleSelectOptionButton.OnItemSelected += OnShuttleSelected;
        SaveAccessButton.OnPressed += OnSavePressed;
        RemoveGroupButton.OnPressed += OnRemovePressed;
    }

    private void OnShuttleSelected(OptionButton.ItemSelectedEventArgs args)
    {
        if (args.Id < 0 || args.Id >= _availableShuttles.Count)
            return;

        _owner.SelectShuttle(_availableShuttles[args.Id]);
    }

    private void OnSavePressed(BaseButton.ButtonEventArgs args)
    {
        if (_selectedShuttle == null)
            return;

        var pressed = _accessButtons.ButtonsList
            .Where(x => x.Value.Pressed)
            .Select(x => x.Key)
            .ToList();

        _owner.SubmitAccess(_selectedShuttle.Value, pressed);
    }

    private void OnRemovePressed(BaseButton.ButtonEventArgs args)
    {
        if (_selectedShuttle == null)
            return;

        _owner.RemoveGroup(_selectedShuttle.Value);
    }

    public void UpdateState(ShuttleIdCardConsoleBoundUserInterfaceState state)
    {
        PrivilegedIdButton.Text = state.IsPrivilegedIdPresent
            ? Loc.GetString("id-card-console-window-eject-button")
            : Loc.GetString("id-card-console-window-insert-button");
        PrivilegedIdLabel.Text = state.PrivilegedIdName;

        TargetIdButton.Text = state.IsTargetIdPresent
            ? Loc.GetString("id-card-console-window-eject-button")
            : Loc.GetString("id-card-console-window-insert-button");
        TargetIdLabel.Text = state.TargetIdName;

        // Populate shuttle list
        _availableShuttles.Clear();
        ShuttleSelectOptionButton.Clear();

        for (var i = 0; i < state.AvailableShuttles.Count; i++)
        {
            var entry = state.AvailableShuttles[i];
            _availableShuttles.Add(entry.ShuttleUid);
            var title = entry.IsOwner
                ? $"{entry.ShuttleName} ({Loc.GetString("shuttle-id-card-console-role-owner")})"
                : $"{entry.ShuttleName} ({Loc.GetString("shuttle-id-card-console-role-crew")})";
            ShuttleSelectOptionButton.AddItem(title, i);
        }

        _selectedShuttle = state.SelectedShuttle;
        if (state.SelectedShuttle != null)
        {
            var index = _availableShuttles.IndexOf(state.SelectedShuttle.Value);
            if (index >= 0)
            {
                ShuttleSelectOptionButton.SelectId(index);
                var entry = state.AvailableShuttles[index];
                ShuttleRoleLabel.Text = entry.IsOwner
                    ? Loc.GetString("shuttle-id-card-console-role-owner-badge")
                    : Loc.GetString("shuttle-id-card-console-role-crew-badge");
            }
        }
        else
        {
            ShuttleRoleLabel.Text = string.Empty;
        }

        ShuttleSelectOptionButton.Disabled = state.AvailableShuttles.Count <= 1;

        // Target card details
        if (state.IsTargetIdPresent)
        {
            var fullName = state.TargetIdFullName ?? Loc.GetString("shuttle-id-card-console-unknown-name");
            var job = state.TargetIdJobTitle ?? Loc.GetString("shuttle-id-card-console-unknown-job");
            TargetCardInfoLabel.Text = Loc.GetString("shuttle-id-card-console-target-info", ("name", fullName), ("job", job));

            var other = state.TargetOtherGroups
                .Where(g => g.ShuttleUid != state.SelectedShuttle)
                .ToList();

            if (other.Count > 0)
            {
                var otherText = string.Join(", ", other.Select(o => $"{o.ShuttleName} ({o.AccessCount})"));
                TargetOtherGroupsLabel.Text = Loc.GetString("shuttle-id-card-console-other-groups", ("groups", otherText));
            }
            else
            {
                TargetOtherGroupsLabel.Text = Loc.GetString("shuttle-id-card-console-no-other-groups");
            }
        }
        else
        {
            TargetCardInfoLabel.Text = Loc.GetString("shuttle-id-card-console-no-target");
            TargetOtherGroupsLabel.Text = string.Empty;
        }

        // Access buttons
        _accessButtons.UpdateState(state.TargetAccessList, state.AllowedModifyAccessList);

        var interfaceEnabled = state.IsPrivilegedIdPresent &&
                               state.IsPrivilegedIdAuthorized &&
                               state.IsTargetIdPresent &&
                               state.SelectedShuttle != null;

        SaveAccessButton.Disabled = !interfaceEnabled;
        RemoveGroupButton.Disabled = !interfaceEnabled || state.TargetAccessList.Count == 0;
    }
}
