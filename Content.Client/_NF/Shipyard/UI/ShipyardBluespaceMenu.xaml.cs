using System;
using System.IO;
using System.Numerics;
using Content.Client.UserInterface.Controls;
using Content.Shared._NF.Shipyard.BUI;
using Robust.Client.AutoGenerated;
using Robust.Client.Graphics;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.GameObjects;
using Robust.Shared.Timing;
using SixLabors.ImageSharp;

namespace Content.Client._NF.Shipyard.UI;

[GenerateTypedNameReferences]
public sealed partial class ShipyardBluespaceMenu : FancyWindow
{
    [Dependency] private readonly IGameTiming _timing = default!;
    [Dependency] private readonly ILogManager _log = default!;

    public event Action<NetEntity>? OnStoreRequested;
    public event Action<NetEntity>? OnRecallRequested;

    private TimeSpan _cooldownEndTime = TimeSpan.Zero;
    private ShipyardConsoleInterfaceState? _lastState;
    private bool _wasOnCooldown;

    public ShipyardBluespaceMenu()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);
        Title = Loc.GetString("shipyard-bluespace-menu-title");
    }

    public void UpdateState(ShipyardConsoleInterfaceState state)
    {
        _lastState = state;
        _cooldownEndTime = state.CooldownEndTime;
        _wasOnCooldown = _cooldownEndTime > _timing.CurTime;
        UpdateCooldownDisplay();

        ShuttleCountLabel.Text = Loc.GetString("shipyard-bluespace-menu-shuttle-count", ("count", state.PlayerShuttles.Count));
        ShuttleGridContainer.RemoveAllChildren();

        if (state.PlayerShuttles.Count == 0)
        {
            NoShuttlesNotice.Visible = true;
            CardsScrollContainer.Visible = false;
            return;
        }

        NoShuttlesNotice.Visible = false;
        CardsScrollContainer.Visible = true;

        ShuttleGridContainer.Columns = Math.Max(1, Math.Min(2, state.PlayerShuttles.Count));

        bool isOnCooldown = _cooldownEndTime > _timing.CurTime;

        foreach (var shuttle in state.PlayerShuttles)
        {
            var card = CreateShuttleCard(shuttle, isOnCooldown, state.HasCaptainAccess);
            ShuttleGridContainer.AddChild(card);
        }
    }

    private Control CreateShuttleCard(PlayerShuttleInfo shuttle, bool isOnCooldown, bool hasCaptainAccess)
    {
        var card = new PanelContainer
        {
            Margin = new Thickness(6),
            MinSize = new Vector2(300, 220),
            HorizontalExpand = true
        };

        bool isStored = shuttle.IsStored;
        bool isDocked = shuttle.IsDocked;

        Robust.Shared.Maths.Color borderColor = isStored
            ? Robust.Shared.Maths.Color.FromHex("#3b82f6") // Vibrant bluespace blue/cyan for stored
            : isDocked
                ? Robust.Shared.Maths.Color.FromHex("#22c55e") // Vibrant green for docked
                : Robust.Shared.Maths.Color.FromHex("#475569"); // Subtle grey for undocked

        Robust.Shared.Maths.Color bgColor = isStored
            ? Robust.Shared.Maths.Color.FromHex("#121824") // Bluespace tinted
            : isDocked
                ? Robust.Shared.Maths.Color.FromHex("#121b15") // Green tinted
                : Robust.Shared.Maths.Color.FromHex("#14171d");

        card.PanelOverride = new StyleBoxFlat
        {
            BackgroundColor = bgColor,
            BorderColor = borderColor,
            BorderThickness = new Thickness(2),
            ContentMarginBottomOverride = 8,
            ContentMarginTopOverride = 8,
            ContentMarginLeftOverride = 10,
            ContentMarginRightOverride = 10
        };

        var mainBox = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Vertical,
            HorizontalExpand = true,
            VerticalExpand = true
        };

        // 1. Header (Name + Status Badge)
        var header = new BoxContainer
        {
            Orientation = BoxContainer.LayoutOrientation.Horizontal,
            HorizontalExpand = true,
            Margin = new Thickness(0, 0, 0, 6)
        };

        var nameLabel = new Label
        {
            Text = shuttle.ShuttleName,
            HorizontalExpand = true,
            ClipText = true,
            FontColorOverride = Robust.Shared.Maths.Color.White
        };
        header.AddChild(nameLabel);

        var statusLabel = new Label
        {
            HorizontalAlignment = HAlignment.Right
        };
        if (isStored)
        {
            statusLabel.Text = Loc.GetString("shipyard-bluespace-menu-status-stored");
            statusLabel.FontColorOverride = Robust.Shared.Maths.Color.FromHex("#60a5fa");
        }
        else if (isDocked)
        {
            statusLabel.Text = Loc.GetString("shipyard-bluespace-menu-status-docked");
            statusLabel.FontColorOverride = Robust.Shared.Maths.Color.FromHex("#4ade80");
        }
        else
        {
            statusLabel.Text = Loc.GetString("shipyard-bluespace-menu-status-undocked");
            statusLabel.FontColorOverride = Robust.Shared.Maths.Color.FromHex("#94a3b8");
        }
        header.AddChild(statusLabel);
        mainBox.AddChild(header);

        // 2. Graphic Container (the photo taken when the shuttle was purchased or stored)
        var graphicPanel = new PanelContainer
        {
            HorizontalExpand = true,
            VerticalExpand = true,
            MinHeight = 120,
            Margin = new Thickness(0, 0, 0, 8),
            PanelOverride = new StyleBoxFlat
            {
                BackgroundColor = Robust.Shared.Maths.Color.FromHex("#0a0d12"),
                BorderColor = isStored ? Robust.Shared.Maths.Color.FromHex("#1e3a5f") : Robust.Shared.Maths.Color.FromHex("#1e2633"),
                BorderThickness = new Thickness(1),
                ContentMarginBottomOverride = 4,
                ContentMarginTopOverride = 4,
                ContentMarginLeftOverride = 4,
                ContentMarginRightOverride = 4
            }
        };

        Texture? displayTexture = null;

        if (shuttle.PhotoData is { Length: > 0 } photoData)
        {
            try
            {
                using var stream = new MemoryStream(photoData);
                displayTexture = Texture.LoadFromPNGStream(stream);
            }
            catch (Exception ex)
            {
                _log.GetSawmill("shipyard").Warning($"Failed to load shuttle photo from PNG: {ex}");
            }
        }

        if (displayTexture != null)
        {
            graphicPanel.AddChild(new TextureRect
            {
                Texture = displayTexture,
                Stretch = TextureRect.StretchMode.KeepAspectCentered,
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center,
                HorizontalExpand = true,
                VerticalExpand = true,
                MinSize = new Vector2(160, 100)
            });
        }
        else
        {
            graphicPanel.AddChild(new Label
            {
                Text = Loc.GetString("shipyard-bluespace-menu-no-preview"),
                FontColorOverride = Robust.Shared.Maths.Color.FromHex("#667382"),
                HorizontalAlignment = HAlignment.Center,
                VerticalAlignment = VAlignment.Center
            });
        }

        mainBox.AddChild(graphicPanel);

        // 3. Action Button
        if (isStored)
        {
            var recallButton = new Button
            {
                Text = Loc.GetString("shipyard-bluespace-menu-button-recall"),
                Disabled = !shuttle.CanRecall || isOnCooldown || !hasCaptainAccess,
                HorizontalExpand = true,
                MinHeight = 32
            };
            var netUid = shuttle.ShuttleUid;
            recallButton.OnPressed += _ => OnRecallRequested?.Invoke(netUid);
            mainBox.AddChild(recallButton);
        }
        else if (isDocked)
        {
            var storeButton = new Button
            {
                Text = Loc.GetString("shipyard-bluespace-menu-button-store"),
                Disabled = !shuttle.CanStore || !hasCaptainAccess,
                HorizontalExpand = true,
                MinHeight = 32
            };
            var netUid = shuttle.ShuttleUid;
            storeButton.OnPressed += _ =>
            {
                storeButton.Disabled = true;
                OnStoreRequested?.Invoke(netUid);
            };
            mainBox.AddChild(storeButton);
        }
        else
        {
            var undockedLabel = new Label
            {
                Text = Loc.GetString("shipyard-bluespace-menu-undocked-info"),
                HorizontalAlignment = HAlignment.Center,
                FontColorOverride = Robust.Shared.Maths.Color.FromHex("#64748b"),
                MinHeight = 32
            };
            mainBox.AddChild(undockedLabel);
        }

        card.AddChild(mainBox);
        return card;
    }

    private void UpdateCooldownDisplay()
    {
        if (_cooldownEndTime > _timing.CurTime)
        {
            var remaining = _cooldownEndTime - _timing.CurTime;
            CooldownLabel.Text = Loc.GetString("shipyard-bluespace-menu-cooldown-active",
                ("time", $"{remaining.Minutes:D2}:{remaining.Seconds:D2}"));
            CooldownLabel.FontColorOverride = Robust.Shared.Maths.Color.FromHex("#ff7070");
        }
        else
        {
            CooldownLabel.Text = Loc.GetString("shipyard-bluespace-menu-cooldown-ready");
            CooldownLabel.FontColorOverride = Robust.Shared.Maths.Color.FromHex("#70ff70");
        }
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateCooldownDisplay();

        bool isOnCooldown = _cooldownEndTime > _timing.CurTime;
        if (_wasOnCooldown && !isOnCooldown && _lastState != null)
        {
            _wasOnCooldown = false;
            UpdateState(_lastState);
        }
    }
}
